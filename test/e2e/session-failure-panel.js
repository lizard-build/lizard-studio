"use strict";

window.runSessionFailurePanelTests = async function () {
  const t = window.__test, checks = [];
  const check = (name, ok) => { if (!ok) throw new Error(name); checks.push(name); };
  const emit = (message) => t.emit({ id: "failure-a", ...message });
  const card = () => document.querySelector(".session-failure");
  const greeting = () => document.querySelector("#chat-greeting");
  t.emit({ type: "ready", version: 31, ok: true, home: "/test", user: "Marianna" });
  t.emit({ type: "agentReady", agent: "codex", ok: true });
  check("ChatGPT starts with its own permission mode", t.posted("start").at(-1)?.agent === "codex" && t.posted("start").at(-1)?.permissionMode === "workspace");
  check("an unused chat shows the greeting", !greeting().classList.contains("hidden"));
  const failure = "error: option '--permission-mode <mode>' argument 'workspace' is invalid. Allowed choices are acceptEdits, auto, bypassPermissions, manual, dontAsk, plan.";
  emit({ type: "error", message: failure });
  emit({ type: "exit", code: 1 });
  emit({ type: "exit", code: 1 });
  check("one failure produces one recovery card", document.querySelectorAll(".session-failure").length === 1 && !document.querySelector(".sys-note.warn"));
  check("startup failure hides the greeting and starter chips", greeting().classList.contains("hidden") && document.querySelector("#chat-setup").classList.contains("hidden"));
  check("the main action names the fix", card().querySelector("button").textContent === "Update helper");
  check("the composer explains that messages will wait", document.querySelector("#composer-input").placeholder === "Write a message to queue" && document.querySelector("#send-btn").getAttribute("aria-label") === "Queue message");
  check("technical output stays collapsed", !card().querySelector("details").open && card().querySelector("pre").textContent === failure);
  check("the fallback command repairs the installation", card().textContent.includes("npx @lizard-build/lizard-studio-host@latest install"));
  const starts = t.posted("start").length;
  t.emit({ type: "agentReady", agent: "codex", ok: true });
  check("readiness refresh cannot retry a failed session on its own", t.posted("start").length === starts);
  const input = document.querySelector("#composer-input");
  input.value = "Keep this queued request";
  input.dispatchEvent(new Event("input", { bubbles: true }));
  input.dispatchEvent(new KeyboardEvent("keydown", { key: "Enter", bubbles: true }));
  await new Promise((resolve) => setTimeout(resolve, 0));
  check("a failed session keeps new prompts queued", t.posted("prompt").length === 0 && t.posted("start").length === starts);
  t.click(".session-failure-action");
  check("Update helper uses the existing update flow", t.posted("selfUpdate").length === 1);
  emit({ type: "selfUpdate", updated: false, error: "offline" });
  check("an update failure keeps the recovery card", !!card());
  emit({ type: "started", cwd: "/test/project", permissionMode: "workspace" });
  check("successful startup removes the failure", !card());
  emit({ type: "error", message: "ChatGPT hasn't sent an update for five minutes. The turn is still running." });
  check("a nonfatal warning never claims that the session stopped", !card());
  emit({ type: "started", cwd: "/test/project", permissionMode: "workspace" });
  emit({ type: "exit", code: 1 });
  check("an exit without stderr offers reconnect", card()?.querySelector("button").textContent === "Reconnect");
  const before = t.posted("start").length;
  t.click(".session-failure-action");
  t.click(".session-failure-action");
  check("reconnect keeps the same agent and permissions", t.posted("start").length === before + 1 && t.posted("start").at(-1).permissionMode === "workspace");
  emit({ type: "started", cwd: "/test/project", permissionMode: "workspace" });
  await new Promise((resolve) => setTimeout(resolve, 0));
  check("reconnect sends the queued prompt once", t.posted("prompt").length === 1);
  emit({ type: "error", code: "AGENT_ROUTING_REQUIRED", message: "<img src=x onerror=alert(1)>" });
  check("untrusted error text stays inert", card().querySelector("pre").textContent.includes("<img") && !card().querySelector("img"));
  check("panel reports no runtime errors", t.errors.length === 0);
  return { passed: checks.length, checks };
};
